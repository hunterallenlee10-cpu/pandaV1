#!/usr/bin/env node
// Phase 4 — write .gitattributes so Git LFS stores every video file and every
// image larger than 1 MB. Re-run after a re-capture, before `git add`.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/config.mjs';

const LIMIT = 1024 * 1024;
const VIDEO = ['mp4', 'webm', 'mov', 'm4v', 'ogv', 'avi', 'mkv'];
const IMAGE_RE = /\.(jpe?g|png|gif|webp|avif|svg|ico|bmp|tiff?)$/i;
const SKIP_DIRS = new Set(['.git', 'node_modules', '.work', '.cache']);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name)) walk(path.join(dir, e.name), out);
    } else out.push(path.join(dir, e.name));
  }
  return out;
}

// gitattributes patterns: escape glob characters, spaces as [[:space:]].
const escape = (p) => p.replace(/[\\*?[\]!#]/g, '\\$&').replace(/ /g, '[[:space:]]');

const big = walk(ROOT)
  .filter((f) => IMAGE_RE.test(f) && fs.statSync(f).size > LIMIT)
  .map((f) => path.relative(ROOT, f).split(path.sep).join('/'))
  .sort();

const lines = [
  '# Git LFS — generated by scripts/06-lfs-attributes.mjs',
  '# All video files:',
  ...VIDEO.flatMap((ext) => [`*.${ext} filter=lfs diff=lfs merge=lfs -text`, `*.${ext.toUpperCase()} filter=lfs diff=lfs merge=lfs -text`]),
  `# Images larger than 1 MB (${big.length}):`,
  ...big.map((p) => `${escape(p)} filter=lfs diff=lfs merge=lfs -text`),
  '',
];
fs.writeFileSync(path.join(ROOT, '.gitattributes'), lines.join('\n'));
console.log(`.gitattributes: LFS for ${VIDEO.length} video extensions + ${big.length} images > 1 MB`);
