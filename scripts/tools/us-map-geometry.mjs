#!/usr/bin/env node
// Generates custom/us-map/us-states.json: compact SVG path data for the US map
// used by the "areas we serve" sections (see custom/us-map/README.md).
//
//   node scripts/tools/us-map-geometry.mjs
//
// Source: the US Census Bureau's cartographic state boundaries (2017, public
// domain) as packaged by us-atlas (states-albers-10m.json), already projected with
// d3.geoAlbersUsa().scale(1300).translate([487.5, 305]) into a 975×610 viewport.
// The output only needs regenerating if the look of the outlines should change;
// the site build reads the committed JSON and never needs these dev tools.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { geoPath } from 'd3-geo';
import { feature, mesh } from 'topojson-client';
import { presimplify, simplify, quantile } from 'topojson-simplify';
import { ROOT } from '../lib/config.mjs';

const require = createRequire(import.meta.url);
const us = require('us-atlas/states-albers-10m.json');

// Keep ~70% of the points: the source is already generalised for a 975-px-wide map,
// and the Chesapeake Bay / Delmarva outlines need detail when zoomed into the East Coast.
const topo = simplify(presimplify(us), quantile(presimplify(us), 0.3));

const FIPS = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE', '11': 'DC',
  '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY',
  '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT',
  '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH',
  '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT',
  '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV', '55': 'WI', '56': 'WY',
};

const pathGen = geoPath().digits(1);
const r1 = (n) => Math.round(n * 10) / 10;

const states = {};
for (const f of feature(topo, topo.objects.states).features) {
  const code = FIPS[f.id];
  if (!code) throw new Error(`Unknown state FIPS code ${f.id}`);
  const [[x0, y0], [x1, y1]] = pathGen.bounds(f);
  const [cx, cy] = pathGen.centroid(f);
  states[code] = { name: f.properties.name, fips: f.id, bbox: [x0, y0, x1, y1].map(r1), centroid: [r1(cx), r1(cy)], d: pathGen(f) };
}

const out = {
  source:
    "US Census Bureau cartographic state boundaries (2017, public domain) via us-atlas@3 states-albers-10m.json, " +
    'projected with d3.geoAlbersUsa().scale(1300).translate([487.5, 305]) into a 975×610 viewport. ' +
    'Generated by scripts/tools/us-map-geometry.mjs — do not edit by hand.',
  projection: { type: 'geoAlbersUsa', scale: 1300, translate: [487.5, 305] },
  viewBox: [0, 0, 975, 610],
  nation: pathGen(feature(topo, topo.objects.nation)),
  borders: pathGen(mesh(topo, topo.objects.states, (a, b) => a !== b)),
  states,
};

const file = path.join(ROOT, 'custom', 'us-map', 'us-states.json');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, JSON.stringify(out) + '\n');
const kb = (s) => `${(s.length / 1024).toFixed(1)} KB`;
console.log(`Wrote ${path.relative(ROOT, file)} (${kb(JSON.stringify(out))}): nation ${kb(out.nation)}, borders ${kb(out.borders)}, ${Object.keys(states).length} states`);
